/**
 * localStorage for tests: Node's own one, without a file to keep it in, does not work, and it hides
 * jsdom's. Install with vi.stubGlobal('localStorage', new MemoryStorage()).
 */
export class MemoryStorage implements Storage {
  private readonly items = new Map<string, string>();
  get length(): number { return this.items.size; }
  clear(): void { this.items.clear(); }
  getItem(key: string): string | null { return this.items.get(key) ?? null; }
  key(index: number): string | null { return [...this.items.keys()][index] ?? null; }
  removeItem(key: string): void { this.items.delete(key); }
  setItem(key: string, value: string): void { this.items.set(key, String(value)); }
}
